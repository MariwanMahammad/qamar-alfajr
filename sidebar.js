    /* ---------- بارکردنی هەڵبژاردنەکان ---------- */
    const store = {
        get: (k, d) => { try { return localStorage.getItem(k) || d; } catch (e) { return d; } },
        set: (k, v) => { try { localStorage.setItem(k, v); } catch (e) {} }
    };
