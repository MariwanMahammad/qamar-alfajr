            box.className = 'sb-alert';
            box.innerHTML = `<span>⚠️</span><span>${n} کارمەند نزیکە لە کۆتایی گرێبەست</span><a href="${ADD.h}?tab=contracts">بینین</a><button type="button" aria-label="✕">✕</button>`;
