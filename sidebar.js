    /* ---------- وەرگێڕان ---------- */
    const SPLIT = /^((?:[\p{Extended_Pictographic}\uFE0F\u200D←→●]|\s)*)([\s\S]*?)([\s:]*)$/u;
    const IDX = { ar: 0, en: 1 };

    // وشە عەرەبییەکان بە ڕەسەنی کوردی دەگۆڕدرێن: سعات => کاتژمێر، دقیقە => خولەک
    const NORM = x => x.replace(/سعات/g, 'کاتژمێر').replace(/دقیقە/g, 'خولەک').replace(/پرێنت/g, 'پرینت');
    // ماوە: «2 ڕۆژ و 3 کاتژمێر» / «1:30 کاتژمێر» / «⚠️ 1 ڕۆژ زیاتر»
    const UNIT_RE = /^[^\d]*\d[\d:.]*\s*(?:ڕۆژ|کاتژمێر|خولەک)/;
    const UNITS = { 'ڕۆژ': ['يوم', 'day(s)'], 'کاتژمێر': ['ساعة', 'hr'], 'خولەک': ['دقيقة', 'min'], 'و': ['و', 'and'], 'زیاتر': ['إضافية', 'over'] };

    function tr(core) {
        if (lang === 'ku') return null;
        const e = DICT[core];
        if (e) return e[IDX[lang]];
        for (const [re, ar, en] of PATTERNS) if (re.test(core)) return core.replace(re, lang === 'ar' ? ar : en);
        if (UNIT_RE.test(core)) return core.split(' ').map(w => UNITS[w] ? UNITS[w][IDX[lang]] : w).join(' ');
        return null;
    }

    function convert(orig) {
        orig = NORM(orig);
        const m = orig.match(SPLIT);
        const t = tr(m[2]);
        return t == null ? orig : m[1] + t + m[3];
    }

    window.royaTr = convert;   // بۆ پرینت و پەڕەی تر: وەرگێڕانی دەقێک بە زمانی ئێستا

    function doText(n) {
        if (n.__ku === undefined) {
            if (!n.nodeValue.trim()) return;
            n.__ku = n.nodeValue;
        }
        const want = convert(n.__ku);
        if (n.nodeValue !== want) n.nodeValue = want;
    }

    const ATTRS = ['placeholder', 'title', 'aria-label'];
    function doAttrs(root) {
        const sel = '[placeholder],[title],[aria-label]';
        const list = root.querySelectorAll ? [...root.querySelectorAll(sel)] : [];
        if (root.matches && root.matches(sel)) list.push(root);
        list.forEach(el => ATTRS.forEach(a => {
            if (!el.hasAttribute(a)) return;
            const k = 'data-ku-' + a;
            if (!el.hasAttribute(k)) el.setAttribute(k, el.getAttribute(a));
            el.setAttribute(a, convert(el.getAttribute(k)));
        }));
    }

    function walk(root) {
        if (root.nodeType === 3) { doText(root); return; }
        if (root.nodeType !== 1) return;
        const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
            acceptNode: n => /^(SCRIPT|STYLE|TEXTAREA)$/.test(n.parentNode.nodeName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
        });
        const nodes = [];
        while (w.nextNode()) nodes.push(w.currentNode);
        nodes.forEach(doText);
        doAttrs(root);
    }

    let origTitle = null;
    function translateAll() {
        if (origTitle === null) origTitle = document.title;
        document.title = origTitle.split(' - ').map(p => convert(p)).join(' - ');
        walk(document.body);
    }

    function setLang(l) {
        lang = l;
        store.set('royaLang', l);
        const h = document.documentElement;
        h.lang = l;
        h.dir = l === 'en' ? 'ltr' : 'rtl';
        translateAll();
        document.querySelectorAll('.sb-lang button').forEach(b => b.classList.toggle('on', b.dataset.lang === l));
        window.dispatchEvent(new Event('royaLangChanged'));
    }

    function setTheme(t) {
        theme = t;
        store.set('royaTheme', t);
        document.documentElement.dataset.theme = t;
        const b = document.getElementById('sbTheme');
        if (b) b.textContent = t === 'light' ? '🌙' : '☀️';
    }

