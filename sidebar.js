        function showSection(key, scroll) {
            const s = SECTIONS[key];
            if (!s || !onEmp) return;
            document.querySelectorAll('.tab-content').forEach(c => c.classList.toggle('active', c.id === 'tab-' + key));
            const ph = document.querySelector('.page-header');
            if (ph) ph.style.display = key === 'home' ? 'none' : '';
            setText('pageIcon', s.icon); setText('pageTitle', s.title); setText('pageSub', s.sub);
            origTitle = s.title + ' - Roya';
            translateAll();
            sb.querySelectorAll('.sub-item').forEach(x => x.classList.toggle('active', x.dataset.tab === key));
            history.replaceState(null, '', key === 'home' ? location.pathname : '?tab=' + key);
            if (scroll) window.scrollTo({ top: 0, behavior: 'smooth' });
        }

